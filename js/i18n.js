  function applyVars(s,vars){
    if(vars) Object.keys(vars).forEach(function(k){ s=s.split('{'+k+'}').join(vars[k]==null?'':vars[k]); });
    return s;
  }

  var i18n={
    dict:DICT,
    lang:'en',
    t:function(key,vars){
      var d=DICT[i18n.lang]||DICT.en;
      var s=d[key]; if(s==null) s=(DICT.en[key]!=null?DICT.en[key]:key);
      return applyVars(s,vars);
    },
    locale:function(){ return i18n.lang==='de'?'de-DE':'en-US'; },
    num:function(n,opts){ try{ return (+n||0).toLocaleString(i18n.locale(),opts); }catch(e){ return String(n); } },
    setLang:function(l){ if(l!=='de'&&l!=='en') return; i18n.lang=l; try{ localStorage.setItem(LSKEY,l); }catch(e){} },
    getLang:function(){ return i18n.lang; },
    init:function(opts){
      opts=opts||{};
      var l=null, saved=null;
      try{ saved=localStorage.getItem(LSKEY); }catch(e){}
      if(saved==='de'||saved==='en') l=saved;
      if(!l){
        var given=opts.lang||(window.LIVEMAP_CONFIG&&window.LIVEMAP_CONFIG.LANG);
        if(given==='de'||given==='en') l=given;
      }
      if(!l){
        var nav=((navigator.language||navigator.userLanguage||'en')+'').toLowerCase();
        l=nav.indexOf('de')===0?'de':'en';
      }
      i18n.lang=l;
      return l;
    }
  };
