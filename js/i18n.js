  function applyVars(s,vars){
    if(vars) Object.keys(vars).forEach(function(k){ s=s.split('{'+k+'}').join(vars[k]==null?'':vars[k]); });
    return s;
  }

  function canonLang(raw){
    if(raw==null) return null;
    var x=String(raw).trim();
    if(!x) return null;
    if(x==='de'||x==='en'||x==='zh-Hans'||x==='zh-Hant') return x;
    x=x.toLowerCase().replace(/_/g,'-');
    if(x==='auto') return null;
    if(x==='de'||x.indexOf('de-')===0) return 'de';
    if(x==='en'||x.indexOf('en-')===0) return 'en';
    if(x==='zh-hant'||x==='zh-tw'||x==='zh-hk'||x==='zh-mo'||x.indexOf('zh-hant')===0||x.indexOf('zh-tw')===0||x.indexOf('zh-hk')===0||x.indexOf('zh-mo')===0) return 'zh-Hant';
    if(x==='zh'||x==='zh-hans'||x==='zh-cn'||x==='zh-sg'||x.indexOf('zh-hans')===0||x.indexOf('zh-cn')===0||x.indexOf('zh-sg')===0||x.indexOf('zh-')===0) return 'zh-Hans';
    return null;
  }
  function browserLang(){
    var list=[];
    try{ if(navigator.languages&&navigator.languages.length) list=[].slice.call(navigator.languages); }catch(e){}
    if(navigator.language) list.push(navigator.language);
    else if(navigator.userLanguage) list.push(navigator.userLanguage);
    for(var i=0;i<list.length;i++){ var c=canonLang(list[i]); if(c) return c; }
    return 'en';
  }
  var i18n={
    dict:DICT,
    lang:'en',
    langs:['de','en','zh-Hans','zh-Hant'],
    t:function(key,vars){
      var d=DICT[i18n.lang]||DICT.en;
      var s=d[key]; if(s==null) s=(DICT.en[key]!=null?DICT.en[key]:key);
      return applyVars(s,vars);
    },
    locale:function(){ return {de:'de-DE',en:'en-US','zh-Hans':'zh-CN','zh-Hant':'zh-TW'}[i18n.lang]||'en-US'; },
    num:function(n,opts){ try{ return (+n||0).toLocaleString(i18n.locale(),opts); }catch(e){ return String(n); } },
    mark:function(){ return {de:'DE',en:'EN','zh-Hans':'简','zh-Hant':'繁'}[i18n.lang]||'EN'; },
    setLang:function(l){
      l=canonLang(l); if(!l) return;
      i18n.lang=l;
      try{ localStorage.setItem(LSKEY,l); }catch(e){}
      try{ document.dispatchEvent(new CustomEvent('sclmw-lang',{detail:l})); }catch(e){}
    },
    getLang:function(){ return i18n.lang; },
    init:function(opts){
      opts=opts||{};
      var l=null, saved=null;
      try{ saved=localStorage.getItem(LSKEY); }catch(e){}
      l=canonLang(saved);
      if(!l) l=canonLang(opts.lang);
      if(!l&&window.LIVEMAP_CONFIG) l=canonLang(window.LIVEMAP_CONFIG.LANG);
      if(!l) l=browserLang();
      i18n.lang=l||'en';
      return i18n.lang;
    }
  };
